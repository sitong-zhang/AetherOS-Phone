static int mkdir_p(const char *path, mode_t mode)
{
    char tmp[AETHER_PKG_MAX_PATH + 64];
    size_t len = strlen(path);
    if (len >= sizeof(tmp)) return -1;
    memcpy(tmp, path, len + 1);
    for (char *p = tmp + 1; *p; p++) {
        if (*p == '/') {
            *p = '\0';
            if (mkdir(tmp, mode) < 0 && errno != EEXIST) return -1;
            *p = '/';
        }
    }
    if (mkdir(tmp, mode) < 0 && errno != EEXIST) return -1;
    return 0;
}

static int rm_nftw_cb(const char *f, const struct stat *sb, int type, struct FTW *ftw)
{
    (void)sb; (void)type; (void)ftw;
    return remove(f);
}

static int rm_recursive(const char *path)
{
    struct stat st;
    if (lstat(path, &st) < 0)
        return errno == ENOENT ? 0 : -1;
    if (!S_ISDIR(st.st_mode))
        return unlink(path);
    /* nftw with FTW_DEPTH removes children before the dir itself. */
    return nftw(path, rm_nftw_cb, 16, FTW_DEPTH | FTW_PHYS);
}

/* Unpack payload files under <dir>. Returns 0 on success. */
static int unpack_files(const struct pkg *p, const char *dir)
{
    for (unsigned i = 0; i < p->nfiles; i++) {
        const struct pkg_file *f = &p->files[i];
        char dst[AETHER_PKG_MAX_PATH + 256];
        int n = snprintf(dst, sizeof(dst), "%s/%s", dir, f->path);
        if (n < 0 || (size_t)n >= sizeof(dst)) {
            fprintf(stderr, "aether-pkg: path too long: %s/%s\n", dir, f->path);
            return -1;
        }
        /* Create parent dirs for subdir paths (components pre-validated). */
        char *slash = strrchr(dst, '/');
        if (slash) {
            *slash = '\0';
            if (mkdir_p(dst, 0755) < 0) {
                fprintf(stderr, "aether-pkg: mkdir %s: %s\n", dst, strerror(errno));
                return -1;
            }
            *slash = '/';
        }
        FILE *out = fopen(dst, "wb");
        if (!out) {
            fprintf(stderr, "aether-pkg: create %s: %s\n", dst, strerror(errno));
            return -1;
        }
        if (f->size > 0 &&
            fwrite(p->payload + f->payload_off, 1, (size_t)f->size, out) != (size_t)f->size) {
            fprintf(stderr, "aether-pkg: write %s: %s\n", dst, strerror(errno));
            fclose(out);
            return -1;
        }
        if (fclose(out) != 0) {
            fprintf(stderr, "aether-pkg: close %s: %s\n", dst, strerror(errno));
            return -1;
        }
        /* Executables must be executable; the manifest marks intent via
         * the exec= field, so make exactly that file 0755. */
        if (strcmp(f->path, p->exec) == 0)
            chmod(dst, 0755);
        else
            chmod(dst, 0644);
        fprintf(stderr, "aether-pkg:   + %s (%llu bytes)\n",
                f->path, (unsigned long long)f->size);
    }
    return 0;
}

/* Read the whole index into a malloc'd buffer (NULL when absent). */
static char *read_index(size_t *len)
{
    FILE *f = fopen(APPS_INDEX, "rb");
    if (!f)
        return NULL;
    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    if (sz < 0) { fclose(f); return NULL; }
    rewind(f);
    char *buf = xmalloc((size_t)sz + 1);
    if (sz > 0 && fread(buf, 1, (size_t)sz, f) != (size_t)sz) {
        fclose(f);
        free(buf);
        return NULL;
    }
    fclose(f);
    buf[sz] = '\0';
    *len = (size_t)sz;
    return buf;
}

/* Rewrite the index dropping any line for `id` and appending a new one.
 * Written to a temp file and renamed for atomicity of the index itself. */
static int index_update(const struct pkg *p)
{
    size_t oldlen = 0;
    char *old = read_index(&oldlen);
    char tmp[PATH_MAX];
    int n = snprintf(tmp, sizeof(tmp), "%s.tmp", APPS_INDEX);
    if (n < 0 || (size_t)n >= sizeof(tmp)) return -1;
    FILE *out = fopen(tmp, "wb");
    if (!out) {
        fprintf(stderr, "aether-pkg: cannot write %s: %s\n", tmp, strerror(errno));
        free(old);
        return -1;
    }
    int dropped = 0;
    if (old) {
        char *save = NULL;
        for (char *line = strtok_r(old, "\n", &save); line;
             line = strtok_r(NULL, "\n", &save)) {
            /* index line: id|name|version|exec|pkg_sha256 */
            char *bar = strchr(line, '|');
            size_t idlen = bar ? (size_t)(bar - line) : strlen(line);
            if (idlen == strlen(p->id) && !memcmp(line, p->id, idlen)) {
                dropped = 1;
                continue;
            }
            fprintf(out, "%s\n", line);
        }
    }
    unsigned char pkgd[AETHER_SHA256_DIGEST_LEN];
    char pkghex[AETHER_SHA256_HEX_LEN];
    aether_sha256(p->content, p->content_len, pkgd);
    hex_encode(pkgd, sizeof(pkgd), pkghex);
    fprintf(out, "%s|%s|%s|%s|%s\n", p->id, p->name, p->version, p->exec, pkghex);
    if (fclose(out) != 0) {
        fprintf(stderr, "aether-pkg: close %s: %s\n", tmp, strerror(errno));
        free(old);
        return -1;
    }
    free(old);
    if (rename(tmp, APPS_INDEX) < 0) {
        fprintf(stderr, "aether-pkg: rename %s -> %s: %s\n",
                tmp, APPS_INDEX, strerror(errno));
        unlink(tmp);
        return -1;
    }
    fprintf(stderr, "aether-pkg: index %s (%s)\n",
            dropped ? "updated (replaced entry)" : "updated (new entry)", APPS_INDEX);
    return 0;
}

static int index_remove(const char *id)
{
    size_t oldlen = 0;
    char *old = read_index(&oldlen);
    if (!old) {
        fprintf(stderr, "aether-pkg: no apps installed (no index)\n");
        return -1;
    }
    char tmp[PATH_MAX];
    int n = snprintf(tmp, sizeof(tmp), "%s.tmp", APPS_INDEX);
    if (n < 0 || (size_t)n >= sizeof(tmp)) { free(old); return -1; }
    FILE *out = fopen(tmp, "wb");
    if (!out) { free(old); return -1; }
    int dropped = 0;
    char *save = NULL;
    for (char *line = strtok_r(old, "\n", &save); line;
         line = strtok_r(NULL, "\n", &save)) {
        char *bar = strchr(line, '|');
        size_t idlen = bar ? (size_t)(bar - line) : strlen(line);
        if (strlen(id) == idlen && !memcmp(line, id, idlen)) {
            dropped = 1;
            continue;
        }
        fprintf(out, "%s\n", line);
    }
    free(old);
    if (fclose(out) != 0) { unlink(tmp); return -1; }
    if (!dropped) {
        fprintf(stderr, "aether-pkg: %s: not installed\n", id);
        unlink(tmp);
        return -1;
    }
    if (rename(tmp, APPS_INDEX) < 0) {
        fprintf(stderr, "aether-pkg: rename index: %s\n", strerror(errno));
        unlink(tmp);
        return -1;
    }
    return 0;
}

