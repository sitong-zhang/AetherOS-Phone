static int cmd_keygen(int argc, char **argv)
{
    if (argc != 4) {
        fprintf(stderr, "usage: aether-pkg keygen <privkey.hex> <pubkey.hex>\n");
        return 2;
    }
    unsigned char pk[AETHER_PKG_PUBKEY_LEN];
    unsigned char sk[AETHER_PKG_PRIVKEY_LEN];
    crypto_sign_keypair(pk, sk);
    char privhex[AETHER_PKG_PRIVKEY_LEN * 2 + 1];
    char pubhex[AETHER_PKG_PUBKEY_LEN * 2 + 1];
    hex_encode(sk, sizeof(sk), privhex);
    hex_encode(pk, sizeof(pk), pubhex);
    FILE *f = fopen(argv[2], "w");
    if (!f) die("cannot write %s: %s", argv[2], strerror(errno));
    fprintf(f, "%s\n", privhex);
    if (fclose(f) != 0) die("cannot close %s", argv[2]);
    f = fopen(argv[3], "w");
    if (!f) die("cannot write %s: %s", argv[3], strerror(errno));
    fprintf(f, "%s\n", pubhex);
    if (fclose(f) != 0) die("cannot close %s", argv[3]);
    printf("aether-pkg: keypair written\n  priv: %s (KEEP ON HOST — release key)\n"
           "  pub : %s (embed in aether-pkg-pubkey.h)\n", argv[2], argv[3]);
    return 0;
}

static int cmd_create(int argc, char **argv)
{
    /* create <out.aepkg> <id> <name> <version> <exec> <file>... */
    if (argc < 8) {
        fprintf(stderr, "usage: aether-pkg create <out.aepkg> <id> <name> <version> "
                        "<exec> <file|src=dst> [file|src=dst...]\n"
                        "  (signing key from $AETHER_PKG_PRIVKEY, 64-byte hex)\n");
        return 2;
    }
    const char *out = argv[2];
    const char *id = argv[3], *name = argv[4], *ver = argv[5], *exec = argv[6];
    char **files = &argv[7];
    int nfiles = argc - 7;

    if (aether_sha256_selftest() != 0)
        die("SHA-256 self-test failed — refusing to create packages with a broken hash");
    if (!valid_id(id)) die("invalid id '%s' ([a-z0-9._-], 1..%d, no leading . or -)",
                           id, AETHER_PKG_MAX_ID);
    if (!valid_name(name)) die("invalid name '%s'", name);
    if (!valid_version(ver)) die("invalid version '%s'", ver);
    if (!valid_relpath(exec)) die("invalid exec path '%s'", exec);
    if ((uint64_t)nfiles > AETHER_PKG_MAX_FILES)
        die("too many files (%d > %d)", nfiles, AETHER_PKG_MAX_FILES);

    const char *privpath = getenv("AETHER_PKG_PRIVKEY");
    if (!privpath || !*privpath)
        die("AETHER_PKG_PRIVKEY (path to 64-byte hex release key) not set");
    unsigned char sk[AETHER_PKG_PRIVKEY_LEN];
    {
        /* The key file may carry comment/header lines (ci/test-signing.key
         * does); take the first line that is exactly 128 hex chars. */
        size_t klen = 0;
        unsigned char *kraw = read_file_bounded(privpath, &klen);
        if (!kraw) die("cannot read signing key %s", privpath);
        int found = 0;
        char *save = NULL;
        char *ktext = xmalloc(klen + 1);
        memcpy(ktext, kraw, klen);
        ktext[klen] = '\0';
        free(kraw);
        for (char *line = strtok_r(ktext, "\n", &save); line;
             line = strtok_r(NULL, "\n", &save)) {
            while (*line == ' ' || *line == '\t' || *line == '\r') line++;
            if (*line == '#' || *line == '\0') continue;
            if (hex_decode(line, sk, sizeof(sk)) == 0) { found = 1; break; }
        }
        free(ktext);
        if (!found)
            die("signing key %s does not contain a 64-byte hex line", privpath);
    }

    /* Build manifest text. */
    char *man = xmalloc(AETHER_PKG_MAX_MANIFEST);
    size_t moff = 0;
    int n = snprintf(man + moff, AETHER_PKG_MAX_MANIFEST - moff,
                     "id=%s\nname=%s\nversion=%s\nexec=%s\n", id, name, ver, exec);
    if (n < 0) die("manifest overflow");
    moff += (size_t)n;

    /* Read each file, hash it, append its manifest line. */
    unsigned char **fdata = xmalloc(sizeof(unsigned char *) * (size_t)nfiles);
    uint64_t *fsize = xmalloc(sizeof(uint64_t) * (size_t)nfiles);
    uint64_t payload_total = 0;
    int exec_seen = 0;
    /* File args accept "src" or "src=dst" (dst = path inside the package,
     * i.e. the install-relative name). exec= must name one of the dsts. */
    for (int i = 0; i < nfiles; i++) {
        char farg[AETHER_PKG_MAX_PATH * 2 + 4];
        char *dst;
        if (strlen(files[i]) >= sizeof(farg))
            die("file argument too long: %s", files[i]);
        strcpy(farg, files[i]);
        dst = strchr(farg, '=');
        const char *src;
        if (dst) {
            *dst = '\0';
            src = farg;
            dst++;
        } else {
            src = farg;
            dst = farg;
        }
        if (!valid_relpath(dst))
            die("invalid package path '%s' (must be a safe relative path)", dst);
        size_t flen = 0;
        fdata[i] = read_file_bounded(src, &flen);
        if (!fdata[i]) die("cannot read file %s", src);
        if ((uint64_t)flen > AETHER_PKG_MAX_FILE)
            die("file %s too large (%llu > %u)", src,
                (unsigned long long)flen, AETHER_PKG_MAX_FILE);
        fsize[i] = (uint64_t)flen;
        payload_total += (uint64_t)flen;
        unsigned char d[AETHER_SHA256_DIGEST_LEN];
        char hex[AETHER_SHA256_HEX_LEN + 1];
        aether_sha256(fdata[i], flen, d);
        hex_encode(d, sizeof(d), hex);
        n = snprintf(man + moff, AETHER_PKG_MAX_MANIFEST - moff,
                     "file=%s %llu %s\n", dst, (unsigned long long)flen, hex);
        if (n < 0 || (size_t)n >= AETHER_PKG_MAX_MANIFEST - moff)
            die("manifest overflow");
        moff += (size_t)n;
        if (strcmp(dst, exec) == 0)
            exec_seen = 1;
    }
    if (!exec_seen)
        die("exec path '%s' is not among the packaged files", exec);

    /* Assemble content = header || manifest || payload. */
    size_t content_len = AETHER_PKG_HEADER_LEN + moff + (size_t)payload_total;
    unsigned char *content = xmalloc(content_len);
    memcpy(content, AETHER_PKG_MAGIC, AETHER_PKG_MAGIC_LEN);
    put_u32le(content + 8, AETHER_PKG_VERSION);
    put_u32le(content + 12, AETHER_PKG_HEADER_LEN);
    put_u64le(content + 16, (uint64_t)moff);
    put_u64le(content + 24, payload_total);
    put_u32le(content + 32, AETHER_PKG_SIG_LEN);
    put_u32le(content + 36, 0);            /* flags */
    memset(content + 40, 0, 24);           /* reserved */
    memcpy(content + AETHER_PKG_HEADER_LEN, man, moff);
    {
        size_t off = AETHER_PKG_HEADER_LEN + moff;
        for (int i = 0; i < nfiles; i++) {
            if (fsize[i] > 0) {
                memcpy(content + off, fdata[i], (size_t)fsize[i]);
                off += (size_t)fsize[i];
            }
            free(fdata[i]);
        }
    }
    free(fdata);
    free(fsize);
    free(man);

    /* Sign content (detached: first 64 bytes of the combined output). */
    unsigned char *sm = xmalloc(AETHER_PKG_SIG_LEN + content_len);
    unsigned long long smlen = 0;
    if (crypto_sign(sm, &smlen, content, (unsigned long long)content_len, sk) != 0)
        die("ed25519 signing failed");
    if (smlen != (unsigned long long)(AETHER_PKG_SIG_LEN + content_len))
        die("ed25519 signing produced unexpected length %llu", smlen);

    FILE *out_f = fopen(out, "wb");
    if (!out_f) die("cannot create %s: %s", out, strerror(errno));
    if (fwrite(content, 1, content_len, out_f) != content_len ||
        fwrite(sm, 1, AETHER_PKG_SIG_LEN, out_f) != AETHER_PKG_SIG_LEN)
        die("cannot write %s: %s", out, strerror(errno));
    if (fclose(out_f) != 0) die("cannot close %s: %s", out, strerror(errno));
    free(sm);
    free(content);

    /* Self-check: verify what we just wrote, before claiming success.
     * If the signing key is NOT the pinned release key, the signature check
     * is meaningless here (it can only fail) — run the structural+digest
     * self-check instead and label the output truthfully, so foreign-key
     * packages can still be produced for negative testing (CI P4). */
    int is_release_key = memcmp(sk + 32, AETHER_PKG_PUBKEY,
                                AETHER_PKG_PUBKEY_LEN) == 0;
    struct pkg chk;
    if (verify_package(out, &chk, is_release_key) != 0)
        die("post-create self-verification FAILED for %s", out);
    free((void *)chk.content);
    if (is_release_key) {
        printf("aether-pkg: created %s\n  id=%s name=%s version=%s exec=%s\n"
               "  files=%d payload=%llu bytes, signed by release key\n",
               out, id, name, ver, exec, nfiles, (unsigned long long)payload_total);
    } else {
        printf("aether-pkg: created %s\n  id=%s name=%s version=%s exec=%s\n"
               "  files=%d payload=%llu bytes\n"
               "  WARNING: signed by a NON-RELEASE key — structure and digests\n"
               "  verified, but every AetherOS guest will REFUSE this package\n"
               "  (its pinned release key does not match). Intended for\n"
               "  negative testing only.\n",
               out, id, name, ver, exec, nfiles, (unsigned long long)payload_total);
    }
    return 0;
}

static int cmd_verify(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "usage: aether-pkg verify <pkg.aepkg>\n");
        return 2;
    }
    if (aether_sha256_selftest() != 0)
        die("SHA-256 self-test failed");
    struct pkg p;
    if (verify_package(argv[2], &p, 1) != 0)
        return 1;
    printf("aether-pkg: %s: OK\n  id=%s name=%s version=%s exec=%s files=%u\n",
           argv[2], p.id, p.name, p.version, p.exec, p.nfiles);
    free((void *)p.content);
    return 0;
}

static int cmd_install(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "usage: aether-pkg install <pkg.aepkg>\n");
        return 2;
    }
    if (aether_sha256_selftest() != 0)
        die("SHA-256 self-test failed");
    struct pkg p;
    if (verify_package(argv[2], &p, 1) != 0)
        return 1;

    if (mkdir_p(APPS_DIR, 0755) < 0)
        die("cannot create %s: %s", APPS_DIR, strerror(errno));

    /* Unpack into a temp dir first; a failure mid-way must not leave a
     * half-installed app that the index claims is present. */
    char tmpdir[PATH_MAX];
    int n = snprintf(tmpdir, sizeof(tmpdir), APPS_DIR "/.tmp.%s", p.id);
    if (n < 0 || (size_t)n >= sizeof(tmpdir)) die("id too long for temp dir");
    rm_recursive(tmpdir);                   /* clear any stale temp */
    if (mkdir(tmpdir, 0755) < 0 && errno != EEXIST)
        die("cannot create %s: %s", tmpdir, strerror(errno));
    if (unpack_files(&p, tmpdir) != 0) {
        fprintf(stderr, "aether-pkg: install failed — cleaning up %s\n", tmpdir);
        rm_recursive(tmpdir);
        free((void *)p.content);
        return 1;
    }

    char finaldir[PATH_MAX];
    n = snprintf(finaldir, sizeof(finaldir), APPS_DIR "/%s", p.id);
    if (n < 0 || (size_t)n >= sizeof(finaldir)) die("id too long for app dir");
    rm_recursive(finaldir);                 /* replace any previous version */
    if (rename(tmpdir, finaldir) < 0) {
        fprintf(stderr, "aether-pkg: rename %s -> %s: %s\n",
                tmpdir, finaldir, strerror(errno));
        rm_recursive(tmpdir);
        free((void *)p.content);
        return 1;
    }

    /* Keep the signed package alongside the app for later re-verify. */
    char pkgdst[PATH_MAX];
    n = snprintf(pkgdst, sizeof(pkgdst), APPS_DIR "/%s.aepkg", p.id);
    if (n < 0 || (size_t)n >= sizeof(pkgdst)) die("id too long for pkg copy");
    {
        size_t rawlen = 0;
        unsigned char *raw = read_file_bounded(argv[2], &rawlen);
        if (raw) {
            FILE *pf = fopen(pkgdst, "wb");
            if (pf) {
                if (fwrite(raw, 1, rawlen, pf) != rawlen)
                    fprintf(stderr, "aether-pkg: warning: cannot keep pkg copy\n");
                fclose(pf);
            }
            free(raw);
        }
    }

    if (index_update(&p) != 0) {
        /* Index is the source of truth for `list`; if it fails, the app
         * dir exists but is not registered — fail the install loudly. */
        fprintf(stderr, "aether-pkg: index update failed — removing %s\n", finaldir);
        rm_recursive(finaldir);
        free((void *)p.content);
        return 1;
    }
    printf("aether-pkg: installed %s %s -> %s (exec %s/%s)\n",
           p.id, p.version, finaldir, finaldir, p.exec);
    free((void *)p.content);
    return 0;
}

static int cmd_list(void)
{
    size_t len = 0;
    char *idx = read_index(&len);
    if (!idx) {
        printf("aether-pkg: no apps installed\n");
        return 0;
    }
    int count = 0;
    char *save = NULL;
    for (char *line = strtok_r(idx, "\n", &save); line;
         line = strtok_r(NULL, "\n", &save)) {
        char *bar1 = strchr(line, '|');
        if (!bar1) continue;
        *bar1 = '\0';
        char *name = bar1 + 1;
        char *bar2 = strchr(name, '|');
        if (!bar2) continue;
        *bar2 = '\0';
        char *ver = bar2 + 1;
        char *bar3 = strchr(ver, '|');
        if (!bar3) continue;
        *bar3 = '\0';
        char *exec = bar3 + 1;
        char *bar4 = strchr(exec, '|');
        if (bar4) *bar4 = '\0';
        printf("  %-24s %-24s %-10s %s/%s/%s\n", line, name, ver, APPS_DIR, line, exec);
        count++;
    }
    free(idx);
    printf("aether-pkg: %d app(s) installed\n", count);
    return 0;
}

static int cmd_remove(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "usage: aether-pkg remove <id>\n");
        return 2;
    }
    const char *id = argv[2];
    if (!valid_id(id)) die("invalid id '%s'", id);
    if (index_remove(id) != 0)
        return 1;
    char dir[PATH_MAX], pkg[PATH_MAX];
    snprintf(dir, sizeof(dir), APPS_DIR "/%s", id);
    snprintf(pkg, sizeof(pkg), APPS_DIR "/%s.aepkg", id);
    rm_recursive(dir);
    unlink(pkg);
    printf("aether-pkg: removed %s\n", id);
    return 0;
}

int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr,
            "aether-pkg — AetherOS package manager (.aepkg v1)\n"
            "commands:\n"
            "  keygen <priv.hex> <pub.hex>          make a release keypair (host)\n"
            "  create <out> <id> <name> <ver> <exec> <file>...   build + sign (host)\n"
            "  verify <pkg>                         check signature + digests\n"
            "  install <pkg>                        verify, unpack, register\n"
            "  list                                 list installed apps\n"
            "  remove <id>                          uninstall\n");
        return 2;
    }
    const char *cmd = argv[1];
    if (!strcmp(cmd, "keygen"))  return cmd_keygen(argc, argv);
    if (!strcmp(cmd, "create"))  return cmd_create(argc, argv);
    if (!strcmp(cmd, "verify"))  return cmd_verify(argc, argv);
    if (!strcmp(cmd, "install")) return cmd_install(argc, argv);
    if (!strcmp(cmd, "list"))    return cmd_list();
    if (!strcmp(cmd, "remove"))  return cmd_remove(argc, argv);
    fprintf(stderr, "aether-pkg: unknown command '%s'\n", cmd);
    return 2;
}
