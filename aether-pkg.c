struct pkg_file {
    char        path[AETHER_PKG_MAX_PATH + 1];
    uint64_t    size;
    char        sha256[AETHER_SHA256_HEX_LEN];
    uint64_t    payload_off;     /* offset within payload region */
};

struct pkg {
    char        id[AETHER_PKG_MAX_ID + 1];
    char        name[AETHER_PKG_MAX_NAME + 1];
    char        version[AETHER_PKG_MAX_VER + 1];
    char        exec[AETHER_PKG_MAX_PATH + 1];
    struct pkg_file files[AETHER_PKG_MAX_FILES];
    unsigned    nfiles;
    const unsigned char *content;   /* header+manifest+payload */
    size_t      content_len;
    const unsigned char *payload;
    uint64_t    payload_len;
};

/* Parse the line-based manifest. Returns 0 on success. The manifest is
 * ALWAYS parsed defensively — it is attacker-controlled input even though
 * a valid signature is required before install (verify parses too). */
static int parse_manifest(struct pkg *p, const char *m, size_t mlen)
{
    memset(p, 0, sizeof(*p));
    size_t pos = 0;
    int have_id = 0, have_name = 0, have_ver = 0, have_exec = 0;

    while (pos < mlen) {
        const char *line = m + pos;
        const char *nl = memchr(line, '\n', mlen - pos);
        size_t linelen = nl ? (size_t)(nl - line) : mlen - pos;
        pos += linelen + 1;

        if (linelen == 0)
            continue;                       /* blank line: skip */
        /* Defensive: manifest text must be NUL-free within the line. */
        if (memchr(line, '\0', linelen))
            return -1;

        const char *eq = memchr(line, '=', linelen);
        if (!eq)
            return -1;
        size_t klen = (size_t)(eq - line);
        const char *val = eq + 1;
        size_t vlen = linelen - klen - 1;

        if (klen == 2 && !memcmp(line, "id", 2)) {
            if (have_id || vlen == 0 || vlen > AETHER_PKG_MAX_ID) return -1;
            memcpy(p->id, val, vlen); p->id[vlen] = '\0';
            if (!valid_id(p->id)) return -1;
            have_id = 1;
        } else if (klen == 4 && !memcmp(line, "name", 4)) {
            if (have_name || vlen == 0 || vlen > AETHER_PKG_MAX_NAME) return -1;
            memcpy(p->name, val, vlen); p->name[vlen] = '\0';
            if (!valid_name(p->name)) return -1;
            have_name = 1;
        } else if (klen == 7 && !memcmp(line, "version", 7)) {
            if (have_ver || vlen == 0 || vlen > AETHER_PKG_MAX_VER) return -1;
            memcpy(p->version, val, vlen); p->version[vlen] = '\0';
            if (!valid_version(p->version)) return -1;
            have_ver = 1;
        } else if (klen == 4 && !memcmp(line, "exec", 4)) {
            if (have_exec || vlen == 0 || vlen > AETHER_PKG_MAX_PATH) return -1;
            memcpy(p->exec, val, vlen); p->exec[vlen] = '\0';
            if (!valid_relpath(p->exec)) return -1;
            have_exec = 1;
        } else if (klen == 4 && !memcmp(line, "file", 4)) {
            if (!have_id) return -1;        /* id must come first */
            if (p->nfiles >= AETHER_PKG_MAX_FILES) return -1;
            /* "path size sha256hex" */
            struct pkg_file *f = &p->files[p->nfiles];
            char sizestr[32], sha[AETHER_SHA256_HEX_LEN + 1];
            unsigned long long sz;
            if (vlen < 3) return -1;
            /* split into three space-separated tokens */
            const char *sp1 = memchr(val, ' ', vlen);
            if (!sp1) return -1;
            size_t plen = (size_t)(sp1 - val);
            const char *rest = sp1 + 1;
            size_t rlen = vlen - plen - 1;
            const char *sp2 = memchr(rest, ' ', rlen);
            if (!sp2) return -1;
            size_t slen = (size_t)(sp2 - rest);
            const char *shastr = sp2 + 1;
            size_t hlen = vlen - plen - 1 - slen - 1;
            if (plen == 0 || plen > AETHER_PKG_MAX_PATH) return -1;
            if (slen == 0 || slen >= sizeof(sizestr)) return -1;
            if (hlen != AETHER_SHA256_HEX_LEN) return -1;
            memcpy(f->path, val, plen); f->path[plen] = '\0';
            if (!valid_relpath(f->path)) return -1;
            memcpy(sizestr, rest, slen); sizestr[slen] = '\0';
            if (sscanf(sizestr, "%llu", &sz) != 1) return -1;
            f->size = (uint64_t)sz;
            if (f->size > AETHER_PKG_MAX_FILE) return -1;
            memcpy(sha, shastr, hlen); sha[hlen] = '\0';
            for (size_t i = 0; i < hlen; i++) {
                char c = sha[i];
                if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f'))) return -1;
            }
            memcpy(f->sha256, sha, sizeof(f->sha256));
            p->nfiles++;
        } else {
            return -1;                      /* unknown key */
        }
    }
    if (!have_id || !have_name || !have_ver || !have_exec || p->nfiles == 0)
        return -1;
    return 0;
}

/* Parse the 64-byte header and validate all length arithmetic. */
static int parse_header(const unsigned char *buf, size_t filelen,
                        uint64_t *manifest_len, uint64_t *payload_len)
{
    if (filelen < AETHER_PKG_HEADER_LEN + AETHER_PKG_SIG_LEN)
        return -1;
    if (memcmp(buf, AETHER_PKG_MAGIC, AETHER_PKG_MAGIC_LEN) != 0)
        return -1;
    if (get_u32le(buf + 8) != AETHER_PKG_VERSION)
        return -1;
    if (get_u32le(buf + 12) != AETHER_PKG_HEADER_LEN)
        return -1;
    if (get_u32le(buf + 32) != AETHER_PKG_SIG_LEN)
        return -1;
    uint64_t ml = get_u64le(buf + 16);
    uint64_t pl = get_u64le(buf + 24);
    if (ml < 1 || ml > AETHER_PKG_MAX_MANIFEST) return -1;
    if (pl > AETHER_PKG_MAX_FILE) return -1;
    /* Overflow-safe total-size check. */
    uint64_t total = (uint64_t)AETHER_PKG_HEADER_LEN + ml + pl + AETHER_PKG_SIG_LEN;
    if (total != (uint64_t)filelen) return -1;
    *manifest_len = ml;
    *payload_len = pl;
    return 0;
}

