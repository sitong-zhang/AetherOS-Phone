/*
 * aether-pkg.c — AetherOS package manager (.aepkg format v1).
 *
 * AetherOS ships its own applications as signed packages instead of
 * "copy binaries into the rootfs". A package is:
 *
 *   [header 64B][manifest][payload][ed25519 signature 64B]
 *
 * The signature covers header+manifest+payload (the whole content region),
 * so any tampering — a flipped byte in the binary, an edited manifest, a
 * truncated file — fails verification before anything is unpacked. The
 * manifest additionally carries a SHA-256 per file, re-checked during
 * unpack as defense in depth.
 *
 * Manifest format (line-based, '\n' terminated, generated by `create`):
 *   id=<app id>                     [a-z0-9._-], 1..48, no leading . or -
 *   name=<display name>             printable, 1..63, no '\n' or '|'
 *   version=<version string>        1..32, no '\n'
 *   exec=<relative path>            validated like a file path below
 *   file=<path> <size> <sha256hex>  one line per payload file
 * The payload is the concatenation of the file contents in manifest order.
 *
 * Commands:
 *   keygen <priv.hex> <pub.hex>                  (host: make a release keypair)
 *   create <out.aepkg> <id> <name> <ver> <exec> <file>...
 *                                                    (host: build + sign;
 *                                                     privkey from $AETHER_PKG_PRIVKEY)
 *   verify <pkg>                                 check signature + digests, no install
 *   install <pkg>                                verify, then unpack to /data/aether/apps/<id>
 *   list                                         show installed apps from the index
 *   remove <id>                                  uninstall an app
 *
 * The guest trusts exactly one public key, embedded in aether-pkg-pubkey.h
 * (generated by `keygen`; committing the PUBLIC key is safe by definition).
 * A package signed by any other key is refused — see ci/hello-foreign.aepkg
 * in CI, which is validly signed by a foreign key and must be rejected.
 *
 * Honesty boundaries (also in README-userland.md §十六):
 *   - The signature proves provenance + integrity of the package bytes. It
 *     says nothing about the safety of the code inside; that is the
 *     sandbox's job (aether-sandbox-run / aether-init sandbox= services).
 *   - The index (/data/aether/apps/index) is a plain text file with no
 *     locking: concurrent installs can race. The system is single-writer
 *     by construction (init/app-runtime serializes installs); a journaling
 *     index is future work.
 *   - No rollback of app data on `remove` beyond deleting the app dir.
 *   - No version/downgrade policy: reinstall (including older versions)
 *     is accepted.
 */
