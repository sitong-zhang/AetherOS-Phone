/* Read a whole file into memory (bounded by AETHER_PKG_MAX_SIZE). */
static unsigned char *read_file_bounded(const char *path, size_t *out_len)
{
    FILE *f = fopen(path, "rb");
    if (!f) {
        fprintf(stderr, "aether-pkg: cannot open %s: %s\n", path, strerror(errno));
        return NULL;
    }
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }
    long sz = ftell(f);
    if (sz < 0 || (unsigned long)sz > AETHER_PKG_MAX_SIZE) {
        fprintf(stderr, "aether-pkg: %s: bad size %ld (limit %u)\n",
                path, sz, AETHER_PKG_MAX_SIZE);
        fclose(f);
        return NULL;
    }
    rewind(f);
    unsigned char *buf = xmalloc((size_t)sz + 1);
    if (sz > 0 && fread(buf, 1, (size_t)sz, f) != (size_t)sz) {
        fprintf(stderr, "aether-pkg: %s: short read\n", path);
        fclose(f);
        free(buf);
        return NULL;
    }
    fclose(f);
    *out_len = (size_t)sz;
    return buf;
}

/*
 * Full verification: signature over header+manifest+payload, then every
 * file digest. On success fills *pkg. Returns 0 on success, -1 on any
 * failure (message already printed).
 *
 * require_release_sig: when 0, the ed25519 check against the pinned
 * AETHER_PKG_PUBKEY is skipped (structural + digest checks only). Only
 * `create` uses that mode, to self-check a package it just signed with a
 * NON-release key (foreign-key test assets) — the guest-side verify/install
 * paths always pass 1, because the pinned key is the only trust anchor.
 */
static int verify_package(const char *path, struct pkg *pkg, int require_release_sig)
{
    size_t filelen = 0;
    unsigned char *buf = read_file_bounded(path, &filelen);
    if (!buf)
        return -1;

    uint64_t mlen = 0, plen = 0;
    if (parse_header(buf, filelen, &mlen, &plen) < 0) {
        fprintf(stderr, "aether-pkg: %s: not a valid .aepkg (bad header)\n", path);
        free(buf);
        return -1;
    }

    size_t content_len = AETHER_PKG_HEADER_LEN + (size_t)mlen + (size_t)plen;

    if (require_release_sig) {
        /* Signature check FIRST — nothing is trusted before this passes.
         * crypto_sign_open copies the WHOLE sm (sig||message, n bytes) into m
         * before stripping the signature (tweetnacl.c: FOR(i,n) m[i]=sm[i]),
         * and it overwrites m[32..63] with the public key — so the output
         * buffer must be >= sig+content bytes and must NOT alias sm. */
        const unsigned char *sig = buf + content_len;
        unsigned char *sm = xmalloc(AETHER_PKG_SIG_LEN + content_len);
        unsigned char *m = xmalloc(AETHER_PKG_SIG_LEN + content_len);
        memcpy(sm, sig, AETHER_PKG_SIG_LEN);
        memcpy(sm + AETHER_PKG_SIG_LEN, buf, content_len);
        unsigned long long mlen_out = 0;
        int rc = crypto_sign_open(m, &mlen_out, sm,
                                  (unsigned long long)(AETHER_PKG_SIG_LEN + content_len),
                                  AETHER_PKG_PUBKEY);
        free(sm);
        free(m);
        if (rc != 0) {
            fprintf(stderr, "aether-pkg: %s: SIGNATURE VERIFICATION FAILED "
                    "(not signed by the AetherOS release key, or bytes modified)\n", path);
            free(buf);
            return -1;
        }
    }

    if (parse_manifest(pkg, (const char *)buf + AETHER_PKG_HEADER_LEN, (size_t)mlen) < 0) {
        fprintf(stderr, "aether-pkg: %s: malformed manifest\n", path);
        free(buf);
        return -1;
    }
    pkg->content = buf;                     /* takes ownership; freed by caller */
    pkg->content_len = content_len;
    pkg->payload = buf + AETHER_PKG_HEADER_LEN + (size_t)mlen;
    pkg->payload_len = plen;

    /* Defense in depth: every file's digest and size, even though the
     * signature already covers the payload. */
    uint64_t off = 0;
    for (unsigned i = 0; i < pkg->nfiles; i++) {
        struct pkg_file *f = &pkg->files[i];
        if (f->size > plen - off) {
            fprintf(stderr, "aether-pkg: %s: payload too small for file %s\n",
                    path, f->path);
            free(buf);
            return -1;
        }
        unsigned char d[AETHER_SHA256_DIGEST_LEN];
        char hex[AETHER_SHA256_HEX_LEN + 1];
        aether_sha256(pkg->payload + off, (size_t)f->size, d);
        hex_encode(d, sizeof(d), hex);
        if (strcmp(hex, f->sha256) != 0) {
            fprintf(stderr, "aether-pkg: %s: file %s sha256 mismatch "
                    "(manifest %s, payload %s)\n", path, f->path, f->sha256, hex);
            free(buf);
            return -1;
        }
        f->payload_off = off;
        off += f->size;
    }
    if (off != plen) {
        fprintf(stderr, "aether-pkg: %s: payload has %llu trailing bytes "
                "(manifest accounts for %llu)\n", path,
                (unsigned long long)(plen - off), (unsigned long long)plen);
        free(buf);
        return -1;
    }
    return 0;
}

