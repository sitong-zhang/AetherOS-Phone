static void die(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    fprintf(stderr, "aether-pkg: ");
    vfprintf(stderr, fmt, ap);
    fprintf(stderr, "\n");
    va_end(ap);
    exit(1);
}

static void *xmalloc(size_t n)
{
    void *p = malloc(n ? n : 1);
    if (!p)
        die("out of memory (%zu bytes)", n);
    return p;
}

/* tweetnacl requires the application to provide randombytes (used only by
 * crypto_sign_keypair on the host). Read the kernel CSPRNG. */
void randombytes(unsigned char *buf, unsigned long long len)
{
    int fd = open("/dev/urandom", O_RDONLY);
    if (fd < 0) {
        /* Key generation without entropy must fail loudly, never silently
         * produce a weak key. */
        die("randombytes: cannot open /dev/urandom: %s", strerror(errno));
    }
    unsigned long long off = 0;
    while (off < len) {
        ssize_t n = read(fd, buf + off, (size_t)(len - off));
        if (n <= 0) {
            close(fd);
            die("randombytes: short read from /dev/urandom");
        }
        off += (unsigned long long)n;
    }
    close(fd);
}

static uint32_t get_u32le(const unsigned char *p)
{
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) |
           ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

static uint64_t get_u64le(const unsigned char *p)
{
    return (uint64_t)get_u32le(p) | ((uint64_t)get_u32le(p + 4) << 32);
}

static void put_u32le(unsigned char *p, uint32_t v)
{
    p[0] = v & 0xff; p[1] = (v >> 8) & 0xff;
    p[2] = (v >> 16) & 0xff; p[3] = (v >> 24) & 0xff;
}

static void put_u64le(unsigned char *p, uint64_t v)
{
    put_u32le(p, (uint32_t)(v & 0xffffffffu));
    put_u32le(p + 4, (uint32_t)(v >> 32));
}

static int hex_decode(const char *hex, unsigned char *out, size_t outlen)
{
    if (strlen(hex) != outlen * 2)
        return -1;
    for (size_t i = 0; i < outlen; i++) {
        unsigned v;
        if (sscanf(hex + 2 * i, "%2x", &v) != 1)
            return -1;
        out[i] = (unsigned char)v;
    }
    return 0;
}

static void hex_encode(const unsigned char *in, size_t len, char *out)
{
    static const char hx[] = "0123456789abcdef";
    for (size_t i = 0; i < len; i++) {
        out[2 * i] = hx[in[i] >> 4];
        out[2 * i + 1] = hx[in[i] & 15];
    }
    out[2 * len] = '\0';
}

/* ------------------------------------------------------------------ */
/* Input validation — every field that ends up in a path is checked      */
/* ------------------------------------------------------------------ */

static int valid_id(const char *s)
{
    size_t n = strlen(s);
    if (n < 1 || n > AETHER_PKG_MAX_ID) return 0;
    if (s[0] == '.' || s[0] == '-') return 0;
    for (size_t i = 0; i < n; i++) {
        char c = s[i];
        if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') ||
              c == '.' || c == '_' || c == '-'))
            return 0;
    }
    return 1;
}

static int valid_name(const char *s)
{
    size_t n = strlen(s);
    if (n < 1 || n > AETHER_PKG_MAX_NAME) return 0;
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)s[i];
        if (c < 0x20 || c > 0x7e || c == '\n' || c == '|') return 0;
    }
    return 1;
}

static int valid_version(const char *s)
{
    size_t n = strlen(s);
    if (n < 1 || n > AETHER_PKG_MAX_VER) return 0;
    for (size_t i = 0; i < n; i++) {
        char c = s[i];
        if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'z') ||
              (c >= 'A' && c <= 'Z') || c == '.' || c == '_' || c == '-' || c == '+'))
            return 0;
    }
    return 1;
}

/* Relative path: no leading '/', no '.'/'..' components, safe charset.
 * Subdirectories allowed (each component validated). */
static int valid_relpath(const char *s)
{
    size_t n = strlen(s);
    if (n < 1 || n > AETHER_PKG_MAX_PATH) return 0;
    if (s[0] == '/' || s[0] == '.') return 0;
    const char *comp = s;
    for (size_t i = 0; i <= n; i++) {
        if (s[i] == '/' || s[i] == '\0') {
            size_t clen = (size_t)(&s[i] - comp);
            if (clen == 0) return 0;                     /* "//" or trailing '/' */
            if (clen == 1 && comp[0] == '.') return 0;
            if (clen == 2 && comp[0] == '.' && comp[1] == '.') return 0;
            for (size_t k = 0; k < clen; k++) {
                char c = comp[k];
                if (!((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
                      (c >= '0' && c <= '9') || c == '.' || c == '_' || c == '-'))
                    return 0;
            }
            comp = s + i + 1;
        }
    }
    return 1;
}

