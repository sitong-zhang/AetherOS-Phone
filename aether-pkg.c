/* ------------------------------------------------------------------ */
/* Layout constants                                                     */
/* ------------------------------------------------------------------ */

#define AETHER_PKG_MAGIC        "AEPKG1\0\0"
#define AETHER_PKG_MAGIC_LEN    8
#define AETHER_PKG_HEADER_LEN   64
#define AETHER_PKG_VERSION      1
#define AETHER_PKG_SIG_LEN      64          /* ed25519 signature bytes   */
#define AETHER_PKG_PUBKEY_LEN   32          /* ed25519 public key bytes  */
#define AETHER_PKG_PRIVKEY_LEN  64          /* tweetnacl secret key bytes*/

/* Hard limits — every one of these is checked before any allocation or
 * unpack, so a malformed/hostile package cannot make us overcommit. */
#define AETHER_PKG_MAX_SIZE     (64u * 1024 * 1024)   /* whole file      */
#define AETHER_PKG_MAX_MANIFEST (1u * 1024 * 1024)    /* manifest bytes  */
#define AETHER_PKG_MAX_FILES    256
#define AETHER_PKG_MAX_FILE     (32u * 1024 * 1024)   /* per-file bytes  */
#define AETHER_PKG_MAX_ID       48
#define AETHER_PKG_MAX_NAME     63
#define AETHER_PKG_MAX_VER      32
#define AETHER_PKG_MAX_PATH     255

#define APPS_DIR       "/data/aether/apps"
#define APPS_INDEX     APPS_DIR "/index"
#define APPS_PKGDIR    "/data/aether/packages"

